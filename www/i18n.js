  const LANGS = ["es", "en", "fr"];
  const NAMES = { es: "Español", en: "English", fr: "Français" };
  let lang = null;
  try { lang = localStorage.getItem("mb_lang"); } catch (e) { /* sin almacenamiento */ }
  if (!LANGS.includes(lang)) {
    const n = (navigator.language || "es").toLowerCase();
    lang = n.startsWith("en") ? "en" : n.startsWith("fr") ? "fr" : "es";
  }
  const D = DICT[lang] || null;
  const T = s => (D && D[s]) || s;
  let busy = false;

  function translateNode(n) {
    if (!D || !n || (n.nodeType !== 1 && n.nodeType !== 9 && n.nodeType !== 11)) return;
    busy = true;
    const w = document.createTreeWalker(n, NodeFilter.SHOW_TEXT);
    let x;
    while ((x = w.nextNode())) {
      const k = x.nodeValue.trim();
      if (k && D[k]) x.nodeValue = x.nodeValue.replace(k, D[k]);
    }
    (n.querySelectorAll ? n.querySelectorAll("[placeholder],[title]") : []).forEach(e => {
      ["placeholder", "title"].forEach(a => { const v = e.getAttribute(a); if (v && D[v]) e.setAttribute(a, D[v]); });
    });
    busy = false;
  }

  function setLang(l) {
    try { localStorage.setItem("mb_lang", l); } catch (e) { /* ignorar */ }
    location.reload();
  }

  document.documentElement.lang = lang;
  window.T = T;
  window.I18n = { lang, T, setLang, LANGS };

  document.addEventListener("DOMContentLoaded", () => {
    // Selector de idioma con banderas (sin texto)
    document.querySelectorAll("[data-lang-switch]").forEach(box => {
      box.innerHTML = "";
      LANGS.forEach(code => {
        const b = document.createElement("button");
        b.type = "button";
        b.className = code === lang ? "on" : "";
        b.title = NAMES[code];
        b.setAttribute("aria-label", NAMES[code]);
        b.innerHTML = '<img src="flags/' + code + '.svg" alt="" />';
        b.addEventListener("click", () => { if (code !== lang) setLang(code); });
        box.appendChild(b);
      });
    });
    if (lang !== "es") document.querySelectorAll("[data-" + lang + "]").forEach(e => { e.textContent = e.getAttribute("data-" + lang); });
    translateNode(document.body);
    if (D) new MutationObserver(ms => {
      if (busy) return;
      ms.forEach(m => { m.addedNodes.forEach(a => translateNode(a.nodeType === 3 ? a.parentNode : a)); if (m.type === "characterData") translateNode(m.target.parentNode); });
    }).observe(document.body, { childList: true, subtree: true, characterData: true });
  });
